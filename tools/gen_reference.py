"""Generate docs/reference.md (the exhaustive option dictionary) from the code.

    python tools/gen_reference.py            # write docs/reference.md
    python tools/gen_reference.py --check    # exit 1 if docs/reference.md is out of date

The option list comes from phrport.options.inventory() (profile keys read by the code, PHRConfig / CoilConfig
fields, qi / Mercier option keywords, every argparse option of qss-run / phrport.phr / qss-coils /
qss-check, PHRPORT_* environment variables); the descriptions from phrport.options.DOC.
tests/test_options_documented.py fails when an option has no description or this file is stale.
"""
import argparse
import os
import sys

os.environ.pop("PHRPORT_PROBLEM", None)          # document the built-in defaults
os.environ.setdefault("JAX_PLATFORMS", "cpu")
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, ROOT)
OUT = os.path.join(ROOT, "docs", "reference.md")

HEADER = """# Option dictionary

<!-- generated by tools/gen_reference.py from the code; do not edit by hand -->

Every option of the package, generated from the code (`python tools/gen_reference.py`): the keys a problem
profile may contain, the command-line flags of `qss-run` (= `python -m phrport.phr`), `qss-coils` and
`qss-check`, and the environment variables. A test fails when an option is added without documentation.

How to read the "Set with" column:

* `profile: phr.aspect_target` is the key `"aspect_target"` in the `"phr"` section of the profile JSON
  (`profile: equilibrium.qi_options.nalpha` is nested in the `"qi_options"` dictionary);
* `--flag` is a command-line flag of `qss-run`; every such flag can also go into the profile's `"run"` section
  as `"flag_name": value` (dashes become underscores, see [profile.md](profile.md));
* an option with both is read from the profile and can be overridden on the command line;
* `(not settable)` options are fixed in the code (listed for completeness).

Defaults are the built-in ones (no profile: PHR's nfp2 QA problem). "Applies to": `all`, `QS`, `QI` (with
`equilibrium.physics: "qi"`) or `finite beta` (with `phr.finite_beta: true`). The meaning, math and paper values
of every constraint are in [constraints.md](constraints.md).

"""


def fmt(v):
    if v is None:
        return "None"
    if isinstance(v, str):
        return v if v else '""'
    if isinstance(v, float):
        return f"{v:g}"
    return str(v).replace("|", "\\|")


def render():
    from phrport import options as O
    inv = O.inventory()
    by = {}
    for r in inv:
        d = O.DOC[r["key"]]
        by.setdefault(d["group"], []).append((r, d))
    out = [HEADER]
    n_settable = sum(1 for r in inv if r["setting"] != "(not settable)")
    out.append(f"**{len(inv)} options** ({n_settable} settable), in {len(by)} groups:\n\n")
    for g, title in O.GROUPS.items():
        if g in by:
            anchor = title.lower().replace(" ", "-").replace("/", "").replace("(", "").replace(")", "")
            anchor = "".join(ch for ch in anchor if ch.isalnum() or ch == "-")
            out.append(f"- [{title}](#{anchor}) ({len(by[g])})\n")
    out.append("\n")
    for g, title in O.GROUPS.items():
        if g not in by:
            continue
        out.append(f"## {title}\n\n| option | set with | default | units | applies to | description |\n"
                   "|---|---|---|---|---|---|\n")
        for r, d in sorted(by[g], key=lambda t: t[0]["key"]):
            name = r["key"].split(".", 1)[1]
            out.append(f"| `{name}` | {r['setting'].replace('|', '/')} | `{fmt(r['default'])}` | {d['units']} | "
                       f"{d['physics']} | {d['desc'].replace('|', '/')} |\n")
        out.append("\n")
    return "".join(out)


if __name__ == "__main__":
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true")
    a = ap.parse_args()
    txt = render()
    if a.check:
        cur = open(OUT).read() if os.path.exists(OUT) else ""
        if cur != txt:
            print("docs/reference.md is out of date: run python tools/gen_reference.py")
            sys.exit(1)
        print("docs/reference.md is up to date")
    else:
        open(OUT, "w").write(txt)
        print("wrote", OUT)
